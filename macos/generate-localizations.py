#!/usr/bin/env python3
"""Generate native .strings tables from the shared Swift localization catalogs."""
import itertools
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / "Sources/PivokiCore/Resources"
latin = set(json.loads((source / "LatinWords.json").read_text()))
for locale in ("en", "tr", "fr"):
    filename = "French.json" if locale == "fr" else "Turkish.json"
    normalized = {}
    for key, localized in json.loads((source / filename).read_text()).items():
        value = key if locale == "en" else localized
        count = len(set(re.findall(r"\{\d\}", key)))
        if count:
            for formats in itertools.product(("%@", "%lld"), repeat=count):
                phrase, translation = key, value
                for index, fmt in enumerate(formats):
                    token = "{" + str(index) + "}"
                    phrase = phrase.replace(token, fmt)
                    translation = translation.replace(token, fmt)
                normalized[phrase] = translation
        else:
            normalized[key] = value
            upper = value.upper()
            if locale == "tr":
                upper = re.sub(r"[^\W\d_]+", lambda match: match[0].upper() if match[0] in latin else match[0].replace("i", "İ").replace("ı", "I").upper(), value)
            normalized[key.upper()] = upper
    dest = root / "Resources/Localizations" / (locale + ".lproj") / "Localizable.strings"
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    lines = ["/* Generated by macos/generate-localizations.py. */"]
    lines.extend(f"{quote(k)} = {quote(v)};" for k, v in sorted(normalized.items()))
    dest.write_text("\n".join(lines) + "\n")
